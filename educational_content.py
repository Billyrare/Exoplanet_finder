def get_educational_content(category='overview'):
    """
    Возвращает образовательные материалы по указанной категории
    
    Args:
        category (str): Категория образовательных материалов
        
    Returns:
        dict: Образовательные материалы
    """
    # Возвращаем запрошенную категорию или обзор, если категория не найдена
    requested_content = EDUCATIONAL_MATERIALS.get(category, EDUCATIONAL_MATERIALS['overview']).copy()
    
    # Добавляем список всех доступных категорий
    requested_content['available_categories'] = list(EDUCATIONAL_MATERIALS.keys())
    
    return requested_content 